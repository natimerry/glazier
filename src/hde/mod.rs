pub unsafe fn hde64_disasm(code: *const c_void, hs: &mut hde64s) -> u32
{
    let mut x: u8;
    let mut c: u8;

    let mut p: *const u8 = code as *const u8;

    let mut cflags: u8;
    let mut opcode: u8;
    let mut pref: u8 = 0;

    let mut ht = HDE64_TABLE.clone();

    let mut m_mod: u8;
    let mut m_reg: u8;
    let mut m_rm: u8;

    let mut disp_size: u8 = 0;
    let mut op64: u8 = 0;


    // up to 16 prefix bytes
    for _ in 0..16 {
        c = *p;
        p = p.add(1);

        match c {
            0xf3 => {
                (*hs).p_rep = c;
                pref |= PRE_F3 as u8;
            }
            0xf2 => {
                (*hs).p_rep = c;
                pref |= PRE_F2 as u8;
            }
            0xf0 => {
                (*hs).p_lock = c;
                pref |= PRE_LOCK as u8;
            }
            0x26 | 0x2e | 0x36 | 0x3e | 0x64 | 0x65 => {
                (*hs).p_seg = c;
                pref |= PRE_SEG as u8;
            }
            0x66 => {
                (*hs).p_66 = c;
                pref |= PRE_66 as u8;
            }
            0x67 => {
                (*hs).p_67 = c;
                pref |= PRE_67 as u8;
            }
            _ => {
                break;
            }
        }
    }


    hs.flags= (pref as u32 )<< 23;
    if !pref{
        pref |= PRE_NONE as u8;
    }

    if (c&0xf0) == 0x40 {
        hs.flags |= F_PREFIX_REX;
    }


    todo!()
}
