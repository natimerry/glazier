use mfa::interpreter::Compile;
use mfa::interpreter::Intrepreter;
use std::env;
use std::fs;
use std::fs::File;
use std::io::Write;
use std::path::Path;
fn main() {
    // Expression: 100 ^ 84 + 0 = 0x30
    let expr = "(a ^ b) - c";
    let out_dir = env::var("OUT_DIR").unwrap();
    let defs_path = Path::new(&out_dir).join("defs.txt");
    let mut file = File::create(&defs_path).unwrap();
    writeln!(file, "a = 100\nb = 83\nc = 7").unwrap();

    let result = Intrepreter::from_source(expr, 1, false);

    match result {
        Ok((_offset, obfuscated)) => {
            let dest_path = Path::new(&out_dir).join("teb_asm.rs");

            assert_eq!(_offset, 0x30);
            let code = format!(
                r#"// Auto-generated by build.rs


#[inline(never)]
pub unsafe fn get_teb() -> *mut TEB {{
    let a: isize = 100;
    let b: isize = 83;
    let c: isize = 7;
    use std::hint::black_box;
    unsafe {{ black_box(crate::utils::readqgsword(std::hint::black_box(({}) as usize))) as *mut TEB }}
}}
"#,
                obfuscated
            );

            fs::write(&dest_path, code).unwrap();
            println!("cargo:rerun-if-changed=build.rs");
        }
        Err(e) => {
            panic!("Failed to parse expression: {}", e);
        }
    }
}
